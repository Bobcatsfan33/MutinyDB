#![allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]
//! **The M4 flagship gate.** One frozen, checksummed incident corpus; one `taint(S)` call; every
//! standing answer database-wide equal to a world that never ingested S; the two-section
//! RecallPlan naming the suspended account first; untainted branches and bystander tenants
//! untouched; a second taint composing; and the taint path killed at every seam without ever
//! half-healing. `docs/M4-TAINT.md` is the contract. This gate runs in CI from this phase forever.

use loom_core::SourceRef;
